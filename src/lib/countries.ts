export function flagFor(iso: string) {
  return iso
    .toUpperCase()
    .replace(/./g, (char) =>
      String.fromCodePoint(127397 + char.charCodeAt(0)),
    );
}

export function findCountry(iso: string) {
  return COUNTRIES.find((country) => country.iso === iso) ?? COUNTRIES[0];
}
